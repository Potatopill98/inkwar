export function getLevel(id) {
  return LEVEL_MAP.get(id) || null;
}

export function chapterOf(id) {
  return Math.min(10, Math.floor((id - 1) / 10) + 1);
}

export function isLevelPlayable(id) {
  return !!LEVEL_MAP.get(id);
}

export function levelUnlocks(level) {
  return {
    units: (level.unlocks && level.unlocks.units) || [],
    heroes: (level.unlocks && level.unlocks.heroes) || [],
  };
}
